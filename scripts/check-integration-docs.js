const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { Interface } = require('ethers');
const ROOT = path.resolve(__dirname, '..');
const digest = data => crypto.createHash('sha256').update(data).digest('hex');
function filesUnder(dir) {
  return fs.readdirSync(path.join(ROOT, dir), {withFileTypes:true}).flatMap(entry => {
    const file = `${dir}/${entry.name}`;
    return entry.isDirectory() ? filesUnder(file) : [file];
  });
}
function reference() {
  let text = '# Current contract ABI reference\n\nGenerated by `npm run integration:refresh` after compilation. Do not edit manually.\n\nExact signatures for the current local artifacts, not a deployment address registry.\nUse each deployed release\'s own ABI. Numeric enum meanings and business rules remain\nin the integration guide and source. Names alone do not establish authorization.\n';
  for (const name of ['SivanAgreementVault','SivanMilestoneVault','SivanClaimVault']) {
    const artifact = JSON.parse(fs.readFileSync(path.join(ROOT, `artifacts/contracts/${name}.sol/${name}.json`)));
    text += `\n## ${name}\n\nSource: [${name}.sol](../contracts/${name}.sol)\n\n`;
    for (const type of ['constructor','function','event','error']) {
      const fragments = new Interface(artifact.abi).fragments.filter(f=>f.type===type).map(f=>f.format('full')).sort();
      text += `### ${type}\n\n\`\`\`text\n${fragments.join('\n')}\n\`\`\`\n\n`;
    }
  }
  return text;
}
function snapshot() {
  const files = [
    ...filesUnder('contracts').filter(f=>!f.startsWith('contracts/test/')),
    ...filesUnder('scripts').filter(f=>/\.(js|cjs)$/.test(f)),
    ...filesUnder('config'), 'hardhat.config.cjs','package.json','package-lock.json',
    '.github/workflows/ci.yml','AGENTS.md',
    'integration/README.md','integration/REVIEW_NOTES.md','integration/CLAIM_VAULT.md',
  ].sort();
  return {schemaVersion:1, files:Object.fromEntries(files.map(f=>[f,digest(fs.readFileSync(path.join(ROOT,f)))]))};
}
function compare(expected, actual) {
  const a=expected.files || {}, b=actual.files || {};
  return [...new Set([...Object.keys(a),...Object.keys(b)])].sort().filter(f=>a[f]!==b[f]);
}
function main() {
  const args=process.argv.slice(2);
  if(args.length && !(args.length===1 && args[0]==='--refresh')) throw new Error('Use no arguments or --refresh');
  const generated=reference(), baseline=snapshot();
  const ref=path.join(ROOT,'integration/CONTRACT_REFERENCE.md'), manifest=path.join(ROOT,'integration/source-baseline.json');
  if(args[0]==='--refresh') {
    fs.writeFileSync(ref,generated);
    fs.writeFileSync(manifest,JSON.stringify(baseline,null,2)+'\n');
    console.log('Integration baseline refreshed. Review generated diffs and semantic documentation before committing.');
    return;
  }
  const saved=JSON.parse(fs.readFileSync(manifest,'utf8'));
  if(saved.schemaVersion!==1) throw new Error('Unsupported integration baseline schema');
  const changed=compare(saved,baseline);
  if(fs.readFileSync(ref,'utf8')!==generated) changed.push('integration/CONTRACT_REFERENCE.md (ABI drift)');
  if(changed.length) throw new Error('Integration review required for:\n'+changed.join('\n')+'\nUpdate guide/review notes, compile, refresh and review baseline.');
  console.log('Integration documentation baseline and vault ABI references match. Semantic review is still required.');
}
if(require.main===module) {try{main();}catch(e){console.error(e.message);process.exitCode=1;}}
module.exports={compare};
